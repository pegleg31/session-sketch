var fs = require("fs");

var FILE = "Session-Sketch.html";
var s = fs.readFileSync(FILE, "utf8");
var before = s.length;
var applied = [], skipped = [];

function count(hay, needle){
  var n = 0, i = 0;
  while((i = hay.indexOf(needle, i)) > -1){ n++; i += needle.length; }
  return n;
}
/* replace `from` with `to`, exactly once. If `to` is already there, the edit
   has been applied on an earlier run — leave it alone. */
function rep(tag, from, to){
  if(s.indexOf(to) > -1){ skipped.push(tag); return; }
  var n = count(s, from);
  if(n !== 1) throw new Error(tag + ": expected its anchor exactly once, found " + n +
    "\n--- anchor ---\n" + from.slice(0, 240));
  s = s.replace(from, to);
  applied.push(tag);
}

/* ---------- 1. the inlined rewrite code, into the result block ---------- */
var START = "/* wave6-enrich:start";
var END   = "/* wave6-enrich:end */";
var src = fs.readFileSync("wave6-enrich.js", "utf8");
/* a script tag anywhere in the inlined source — even inside a comment — would
   split a block in the wrong place for build-portal.js and the regression */
if(/<\/?script/i.test(src)) throw new Error("wave6-enrich.js contains a literal script tag; remove it");
var block =
  "/* wave6-enrich:start (generated by build-enrich-inline.js from wave6-enrich.js — do not hand-edit) */\n" +
  src.replace(/\s*$/, "") + "\n" +
  "/* wave6-enrich:end */\n";

if(s.indexOf(START) > -1){
  var a = s.indexOf(START), b = s.indexOf(END) + END.length + 1;
  s = s.slice(0, a) + block + s.slice(b);
  applied.push("1. re-inlined wave6-enrich.js");
} else {
  /* the same comment text also appears in the CSS, so anchor on the JS that
     follows it */
  var HOOK = "/* ---------- result view ---------- */\nfunction whyPrimary(c){";
  if(count(s, HOOK) !== 1) throw new Error("could not find the result-view script header exactly once");
  s = s.replace(HOOK, "/* ---------- result view ---------- */\n" + block + "function whyPrimary(c){");
  applied.push("1. inlined wave6-enrich.js into the result block");
}

/* ---------- 2. accessors prefer the rewritten line ---------- */
